class TestSmartRelocCompare:
    """smart_reloc_compare over real parsed typed records from the fixture."""

    def _records(self, symbol: str) -> list[CoffRelocRecord]:
        return parse_obj_relocs_full(FIXTURES / "mini.obj", symbol)

    def test_dir32_valid_and_invalid(self) -> None:
        records = self._records("_func1")
        name_to_va = {"_extern_var": EXTERN_VA, "_decoy": DECOY_VA}
        # Valid: target imm32 == catalog VA.
        good = FUNC1[:5] + struct.pack("<I", EXTERN_VA) + FUNC1[9:]
        matched, count, total, valid, invalid = smart_reloc_compare(
            FUNC1, good, records, name_to_va, section_va=FUNC1_VA
        )
        assert matched and count > 0 and valid == [5] and invalid == []
        # Invalid: target imm32 points at a *different* cataloged symbol —
        # the only case smart_reloc_compare can prove wrong for DIR32.
        bad = FUNC1[:5] + struct.pack("<I", DECOY_VA) + FUNC1[9:]
        matched, count, total, valid, invalid = smart_reloc_compare(
            FUNC1, bad, records, name_to_va, section_va=FUNC1_VA
        )
        assert not matched and invalid == [5]

    def test_rel32_valid_and_invalid(self) -> None:
        records = self._records("_func2")
        name_to_va = {"_callee": CALLEE_VA}
        # Valid: imm32 == callee_va - pc, pc = section_va + offset + 4.
        pc = FUNC2_VA + 4 + 4
        imm = (CALLEE_VA - pc) & 0xFFFFFFFF
        good = FUNC2[:4] + struct.pack("<I", imm) + FUNC2[8:]
        matched, count, total, valid, invalid = smart_reloc_compare(
            FUNC2, good, records, name_to_va, section_va=FUNC2_VA
        )
        assert matched and valid == [4] and invalid == []
        # Invalid: imm32 for a different target.
        bad = FUNC2[:4] + struct.pack("<I", (EXTERN_VA - pc) & 0xFFFFFFFF) + FUNC2[8:]
        matched, count, total, valid, invalid = smart_reloc_compare(
            FUNC2, bad, records, name_to_va, section_va=FUNC2_VA
        )
        assert not matched and invalid == [4]


class TestFlirtPipeline:
    """gen_flirt_pat → python-flirt .pat → scan mini_pe.exe, all offline."""

    def test_parse_archive_yields_member(self) -> None:
        members = list(parse_archive(str(FIXTURES / "mini.lib")))
        assert [(name, data) for name, data in members] and members[0][0] == "mini.obj"

    def test_parse_coff_obj_extracts_both_functions(self) -> None:
        ((_, obj_data),) = parse_archive(str(FIXTURES / "mini.lib"))
        funcs = {name: (code, relocs) for name, code, relocs in parse_coff_obj(obj_data)}
        # gen_flirt_pat keeps the raw section slice (int3 padding included).
        assert funcs["_func1"] == (FUNC1 + b"\xcc" * 5, {5, 6, 7, 8})  # DIR32 spans 4 bytes
        assert funcs["_func2"] == (FUNC2 + b"\xcc\xcc", {4, 5, 6, 7})  # REL32 spans 4 bytes

    def test_bytes_to_pat_line_masks_relocs(self) -> None:
        line = bytes_to_pat_line("_func1", FUNC1, {5, 6, 7, 8})
        assert line.startswith("558BEC8B05........5DC3")  # reloc slot masked
        assert line.endswith(":0000 _func1")

    def test_pat_line_scans_pe_text(self) -> None:
        import flirt  # python-flirt package (module name is flirt)

        line = bytes_to_pat_line("_func1", FUNC1, {5, 6, 7, 8})
        sigs = flirt.parse_pat(line + "\n---\n")  # .pat files end with a --- terminator
        assert sigs, "python-flirt must accept the generated .pat line"
        matcher = flirt.compile(sigs)

        info = load_binary(FIXTURES / "mini_pe.exe")
        text = info.sections[".text"]
        code_data = info.data[text.file_offset : text.file_offset + text.raw_size]
        matches = matcher.match(code_data[:1024])
        names = {n[0] if isinstance(n, tuple) else str(n) for m in matches for n in m.names}
        assert "_func1" in names
