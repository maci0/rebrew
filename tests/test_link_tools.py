def test_load_data_symbols(tmp_path: Path) -> None:
    meta = tmp_path / "rebrew-data.toml"
    meta.write_text(
        '["SERVER.0x10027000"]\nname = "g_a"\nsection = ".data"\ntype = "int"\n'
        '["SERVER.0x10027004"]\nname = "g_b"\nsection = ".bss"\n'
        '["SERVER.0x10027010"]\nname = "g_c"\nsection = ".data"\n',
        encoding="utf-8",
    )
    syms = load_data_symbols(meta)
    assert [(a, n) for a, n, _ in syms] == [
        (0x10027000, "g_a"),
        (0x10027010, "g_c"),
    ]


def test_gen_link_stubs(tmp_path: Path) -> None:
    meta = tmp_path / "rebrew-data.toml"
    meta.write_text('["SERVER.0x10027000"]\nname = "g_a"\nsection = ".data"\n', encoding="utf-8")
    text = gen_link_stubs(meta)
    assert "char g_a[1] = {0};" in text
    assert "g_bss_tail[0x400000]" in text
    assert "AUTO-GENERATED by rebrew gen-link-stubs" in text


# ---------------------------------------------------------------------------
# gen-layout --data-gap
# ---------------------------------------------------------------------------


def _mk_pe_with_data(data_size: int = 0x100) -> bytes:
    """Minimal 4-section PE (text/rdata/data/reloc) with a .data raw region."""
    text_va, rdata_va, data_va, reloc_va = 0x1000, 0x2000, 0x3000, 0x4000
    raw_off = 0x200
    text_raw = b"\xc3" + b"\x00" * (0x1000 - 1)
    data_raw = bytes(range(data_size)) + b"\x00" * (0x200 - data_size)

    dos = bytearray(0x80)
    dos[0:2] = b"MZ"
    struct.pack_into("<I", dos, 0x3C, 0x80)
    coff = struct.pack("<HHIIIHH", 0x14C, 4, 0, 0, 0, 0xE0, 0x0102)
    opt = bytearray(struct.pack("<H", 0x10B))
    opt += b"\x00" * (0xE0 - 2)
    struct.pack_into("<I", opt, 0x38, 0x1000)  # SizeOfImage
    secs = b""
    for name, vs, va, raw_sz, chars in (
        (b".text\x00\x00\x00", 0x1000, text_va, 0x1000, 0x60000020),
        (b".rdata\x00\x00", 0x200, rdata_va, 0x200, 0x40000040),
        (b".data\x00\x00\x00", 0x200, data_va, 0x200, 0xC0000040),
        (b".reloc\x00\x00", 0x200, reloc_va, 0x200, 0x42000040),
    ):
        secs += struct.pack("<8sIIIIIIHHI", name, vs, va, raw_sz, raw_off, 0, 0, 0, 0, chars)
        raw_off += raw_sz
    hdrs = dos + b"PE\x00\x00" + coff + opt + secs
    hdrs += b"\x00" * (0x200 - len(hdrs))
    out = bytearray(hdrs)
    out += text_raw  # .text at 0x200 .. 0x1200
    out += b"\x00" * 0x200  # .rdata at 0x1200
    out += data_raw  # .data at 0x1400
    out += b"\x00" * 0x200  # .reloc at 0x1600
    return bytes(out)


def test_gen_data_restore() -> None:
    pe = _mk_pe_with_data(0x100)
    text = gen_data_restore(pe, "TEST", 0x40)
    assert "// DATA: TEST 0x3040" in text
    assert "g_data_restore_gap[0x1c0]" in text
    assert "0x40,0x41" in text  # bytes [0x40:0x100] of the .data raw
    assert text.count("0x") > 5


