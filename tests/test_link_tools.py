def test_read_data_vs(tmp_path: Path) -> None:
    pe = _mk_pe_with_data()
    p = tmp_path / "out.dll"
    p.write_bytes(pe)
    assert read_data_vs(p) == 0x200


def test_find_link_cmd(tmp_path: Path) -> None:
    build = tmp_path / "build" / "CMakeFiles" / "server_dll.dir"
    build.mkdir(parents=True)
    (build / "link.txt").write_text(
        "/nologo /out:/abs/server.dll /pdb:/abs/server.pdb /dll a.obj", encoding="utf-8"
    )
    link_cwd, tpl, target_dir = find_link_cmd(tmp_path)
    assert link_cwd == tmp_path / "build"
    assert target_dir == build
    assert "/out:{out}" in tpl and "/pdb:{out}.pdb" in tpl
    assert "{options}" in tpl
