from rebrew.order_sources import file_va, order_sources

# ---------------------------------------------------------------------------
# order-sources
# ---------------------------------------------------------------------------


def _mk_src(tmp_path: Path, name: str, va: int | None) -> Path:
    p = tmp_path / name
    content = "int x;\n"
    if va is not None:
        content += f"// FUNCTION: server.dll 0x{va:x}\nvoid f(void) {{}}\n"
    p.write_text(content)
    return p


def test_file_va(tmp_path: Path) -> None:
    assert file_va(_mk_src(tmp_path, "a.c", 0x10002000)) == 0x10002000
    assert file_va(_mk_src(tmp_path, "b.c", None)) is None


def test_order_sources(tmp_path: Path) -> None:
    a = _mk_src(tmp_path, "a.c", 0x10003000)
    b = _mk_src(tmp_path, "b.c", 0x10001000)
    c = _mk_src(tmp_path, "c.c", None)
    ordered, excluded = order_sources([a, c, b], {}, set())
    assert ordered == [b, a, c]


def test_order_sources_first_va_and_exclude(tmp_path: Path) -> None:
    z = _mk_src(tmp_path, "zlib.c", None)
    g = _mk_src(tmp_path, "game.c", 0x10001000)
    dead = _mk_src(tmp_path, "uncompr.c", None)
    ordered, excluded = order_sources([z, g, dead], {"zlib.c": 0x10000000}, {"uncompr.c"})
    assert ordered == [z, g]
    assert excluded == ["uncompr.c"]


