def render_coverage_toml(
    target_name: str,
    data: dict[str, Any],
    *,
    previous: dict[str, Any] | None = None,
    verify_rows: Sequence[tuple[Any, ...]] | None = None,
) -> str:
    """Return the whole TOML document for one target, as a string.

    *data* is one catalog snapshot as ``load_coverage_datasets`` returns it.
    *previous* is the prior document for the same target (see
    :func:`_read_previous`); its ``functions`` statuses are this build's
    history baseline and its ``history`` array is carried forward.  A document
    that is missing, unreadable or of another :data:`_TOML_VERSION` contributes
    no history — the replacement for ``build_db``'s version-check / unlink /
    ``--force`` dance, and the reason there is no sidecar here to reset.

    *verify_rows* is :func:`rebrew.build_db.import_verify_rows`'s answer, and it
    keeps that function's three states: ``None`` (the verify cache says nothing
    about this target) carries *previous*'s ``verify_results`` forward verbatim,
    ``[]`` writes none, and a list writes those rows.  Three states rather than
    a default because a cache that never mentioned the target is not evidence
    that the target's verdicts went away.

    Nothing is written and nothing is read, so the same call is what the tests,
    the writer and an in-memory check all use.
    """
    if previous is not None and previous.get("version") != _TOML_VERSION:
        # Same data loss as the unreadable-file case _read_previous logs, and
        # the rebuild below replaces the file, so it has to be said out loud.
        log.warning(
            "coverage_toml: prior document for %s carries version %r, not %r; "
            "the rebuild carries no history",
            target_name,
            previous.get("version"),
            _TOML_VERSION,
        )
    prev = previous if previous is not None and previous.get("version") == _TOML_VERSION else {}
    fn_rows = dedupe_by_va(
        _function_rows(target_name, data), target_name=target_name, table="function"
    )
    g_rows = dedupe_by_va(_global_rows(target_name, data), target_name=target_name, table="global")
    # VA order: a text file has no index, so its row order IS the order a
    # reader walks.  Sorting here means that order means something, instead of
    # inheriting the catalog's JSON key order, which is stable but arbitrary.
    fn_rows.sort(key=_row_va)
    g_rows.sort(key=_row_va)

    sections: dict[str, Any] = data.get("sections", {})
    if verify_rows is None:
        # Copied, not aliased: a caller that mutated the document it handed in
        # would otherwise change what the next render writes.
        previous_rows = prev.get("verify_results")
        verify_list: list[Any] = (
            [dict(row) for row in previous_rows if isinstance(row, dict)]
            if isinstance(previous_rows, list)
            else []
        )
    else:
        verify_list = [_rows_from(_VERIFY_RESULTS_COLUMNS, row) for row in verify_rows]
    history = _merge_history(prev.get("functions"), prev.get("history"), fn_rows)

    lines: list[str] = [_HEADER]
    lines.append(f"version = {_TOML_VERSION}")
    lines.append(_kv("target", target_name))
    # Bulk arrays first: a bare key after a table header belongs to THAT table.
    lines.extend(_kv_block("functions", [_rows_from(_FUNCTION_COLUMNS, r) for r in fn_rows]))
    lines.extend(_kv_block("globals", [_rows_from(_GLOBAL_COLUMNS, r) for r in g_rows]))
    lines.extend(_kv_block("verify_results", verify_list))
    lines.extend(_kv_block("history", history))
    lines.append("")
    lines.append("[metadata]")
    lines.append(_kv("paths", data.get("paths", {})))
    for sec_name, sec in sections.items():
        lines.append("")
        lines.extend(_section_table(sec_name, sec))
    return "\n".join(lines) + "\n"


def write_coverage_toml(
    root_dir: Path,
    *,
    target: str | None = None,
    force: bool = False,
    regen: bool = False,
    json_output: bool = False,
) -> list[Path]:
    """Write ``db/coverage-<target>.toml`` for each dataset; return the paths written.

    The catalog inputs and every normalization come from
    :func:`rebrew.build_db.load_coverage_datasets` and its helpers, so this
    writer and ``build_db`` answer the same questions the same way.  What it
    does not inherit is the SQLite-only ceremony: there is no schema version to
    check, no ``--force`` unlink of a previous file, and no sidecars to
    recover.

    *force* is accepted for signature symmetry with
    :func:`rebrew.build_db.build_db` and has no effect: a stale file is fully
    replaced on every write, so there is nothing to force past.  So is *regen*:
    the catalog analysis always runs in this process.

    Returns the paths written, in dataset order.  Writes nothing else — the
    caller reports.
    """
    db_directory = resolve_db_dir(root_dir, json_output=json_output)
    datasets = load_coverage_datasets(
        root_dir,
        db_directory,
        target=target,
        json_output=json_output,
        regen=regen,
    )
    written: list[Path] = []
    for target_name, data in datasets:
        path = db_directory / f"coverage-{target_name}.toml"
        # The whole read-modify-write holds one write lock per target, like the
        # other tool-owned stores.  atomic_write_text alone stops a torn file
        # but not a lost update: two builders for one target (the dashboard
        # regenerating while a manual `build-db` runs) each read the same
        # `previous`, each carry its own delta rows into `history`, and the
        # second replace drops the first's history and restamps
        # `verified_at` — a silent reset of every chart, invisible until the
        # retention window rolls the rows off.  The lock is per target, so
        # builds of different targets still run concurrently.
        with _coverage_write_lock(root_dir, target_name):
            previous = _read_previous(path)
            # The verify cache is read here, not inside render: render stays a
            # pure function of its arguments (see its docstring), and the
            # previous document is already in hand for it to read the "was
            # this measured identically before" mapping out of.
            verify_rows = import_verify_rows(
                root_dir,
                target_name,
                _previous_measured(previous),
                # Only the fallback stamp: a cache file whose mtime cannot be
                # read still has to be dateable, and the moment of this build
                # is the honest answer.
                datetime.now(UTC).isoformat(),
            )
            atomic_write_text(
                path,
                render_coverage_toml(target_name, data, previous=previous, verify_rows=verify_rows),
            )
        written.append(path)
    return written


# ---------------------------------------------------------------------------
# Reader — the one snapshot type both dashboards import
# ---------------------------------------------------------------------------
#
# The dashboards used to read ``coverage.db`` inside a read transaction, so a
# page never paired one build's cells with the next build's functions.  A frozen
# snapshot is that property in the type system: every collection is a tuple or a
# ``MappingProxyType``, so a caller cannot edit the value it was handed and the
# next caller sees the same thing.  Every aggregate the writer does not store
# (per-section buckets, byte coverage, the by-VA index) is computed here once,
# at load, and never by a consumer.


class CoverageTomlError(RebrewError):
    """A coverage TOML document is missing, malformed, or of another version."""


def _db_directory(root_dir: Path) -> Path:
    """The directory this reader globs, resolved without ever exiting.

    ``build_db.resolve_db_dir`` is the writer's resolver and calls typer's
    ``error_exit`` on a broken ``rebrew-project.toml``; that is right for a CLI
    and wrong here, because both dashboards call these readers inside a WSGI
    request and a ``SystemExit`` there takes the server down instead of
    answering one target with an error page.  ``rebrew.workspace.db_dir`` is the
    same path computation without the exit — the two share it, so they cannot
    disagree on where the file lives — and its one failure is converted into
    this module's own error type, which every caller already handles.
    """
    try:
        return db_dir(root_dir)
    except WorkspaceConfigError as exc:
        # read_config's message already names the file and says what is wrong
        # with it; re-adding the path would print it twice.
        raise CoverageTomlError(str(exc)) from exc


#: The one cell state a section's byte coverage excludes.  This is not a new
#: definition: it is recoverage's ``server.SECTION_STATS_SQL``
#: (``CASE WHEN state != 'none'``) and ``potato``'s, restated here because the
#: sentence has to survive the move off SQLite.
_UNCOVERED_CELL_STATE = "none"

#: Filename shape ``write_coverage_toml`` writes and this reader globs for.
_FILENAME_PREFIX = "coverage-"
_FILENAME_SUFFIX = ".toml"


@dataclass(frozen=True, slots=True)
class Cell:
    """One ``cells`` row.

    ``label`` and ``parent_function`` are the two optional columns build_db
    allows NULL; TOML spells NULL ``""``, so the reader hands back the empty
    string it stores rather than inventing a distinction the file cannot carry.
    """

    start: int
    end: int
    span: int
    state: str
    functions: tuple[str, ...]
    label: str
    parent_function: str

    @property
    def size(self) -> int:
        """Byte length of the span.  Derived, never stored (see the docstring)."""
        return self.end - self.start


@dataclass(frozen=True, slots=True)
class Section:
    """One ``[sections."…"]`` table plus everything derivable from its cells.

    ``buckets`` maps a cell state to the bytes it covers, so it sums to the
    section's cell bytes.  The names of the derived fields are this reader's
    own: nothing stores them, so nothing can disagree with them.
    """

    name: str
    #: Section VA, ``None`` when the catalog had none (``""`` in the file).
    va: int | None
    size: int
    #: File offset of the section's raw data, ``None`` when the catalog had
    #: none (``""`` in the file).  A ``.bss`` is uninitialised and has no file
    #: offset at all; the SQLite row stored NULL for it, and reading that NULL
    #: back as 0 is what let ``/asm`` and ``/bytes`` serve real bytes from the
    #: start of the file for a section that has none.  Absent and 0 are
    #: different answers here, so the file's `""` is not collapsed to 0.
    file_offset: int | None
    unit_bytes: int
    columns: int
    cells: tuple[Cell, ...]
    buckets: Mapping[str, int] = field(init=False)
    covered_bytes: int = field(init=False)
    coverage_pct: float = field(init=False)
    cell_count: int = field(init=False)
    bucket_counts: Mapping[str, int] = field(init=False)

    def __post_init__(self) -> None:
        # Computed here, not in the loader: a Section built by a test or by a
        # consumer carries the same numbers as one the reader built, so there is
        # no second formula to keep in step.
        buckets: dict[str, int] = {}
        for cell in self.cells:
            buckets[cell.state] = buckets.get(cell.state, 0) + cell.size
        total = sum(buckets.values())
        covered = total - buckets.get(_UNCOVERED_CELL_STATE, 0)
        object.__setattr__(self, "buckets", MappingProxyType(buckets))
        object.__setattr__(self, "covered_bytes", covered)
        # Floored, like every other coverage figure in the codebase: to
        # nearest, one unaccounted byte in a 100000-byte section reads 100.0%
        # here while ``catalog.grid`` beside it says 99.99.  An empty section
        # (a target with no cells for it) reports 0.0 instead of dividing by
        # zero.
        object.__setattr__(self, "coverage_pct", floor_pct(covered, total, 2))
        object.__setattr__(self, "cell_count", len(self.cells))
        object.__setattr__(self, "bucket_counts", MappingProxyType(_bucket_counts(self.cells)))


#: What :func:`_bucket_counts` collapses each stored state into.  The database
#: computed these with recoverage's ``server.SECTION_STATS_SQL`` CASE sums; this
#: is that SELECT's rule, restated once because both dashboards serve the counts
#: and a second copy would be a second answer.  ``verified`` is an exact match,
#: ``near_matching`` is the near-match bucket, and a state with no name of its
#: own lands in ``other``.
_BUCKET_OF_STATE: Mapping[str, str] = MappingProxyType(
    {
        "exact": "exact",
        "verified": "exact",
        "reloc": "reloc",
        "near_match": "near_match",
        "near_matching": "near_match",
        "stub": "stub",
        "padding": "padding",
        "data": "data",
        "thunk": "thunk",
        "none": "none",
        "proven": "proven",
        "size_mismatch": "size_mismatch",
    }
)

#: Every key :func:`_bucket_counts` emits, in the order the served dicts use.
_BUCKET_KEYS: tuple[str, ...] = (
    "total_cells",
    "exact",
    "reloc",
    "near_match",
    "stub",
    "padding",
    "data",
    "thunk",
    "none",
    "proven",
    "size_mismatch",
    "other",
)


def _bucket_counts(cells: tuple[Cell, ...]) -> dict[str, int]:
    """Cell COUNTS per served bucket, including the ``other`` catch-all.

    ``other`` is what makes ``total_cells`` equal the sum of the counted
    buckets: rebrew stores verdict states the named buckets do not cover
    (``compile_error``, ``unknown``, the data drift/unchecked verdicts), and a
    section holding one of those undercounts without it.  The database computed
    the same number in SQL, so this is that expression rather than a new rule.
    """
    counts = dict.fromkeys(_BUCKET_KEYS, 0)
    counts["total_cells"] = len(cells)
    for cell in cells:
        counts[_BUCKET_OF_STATE.get(cell.state, "other")] += 1
    return counts


@dataclass(frozen=True, slots=True)
class Function:
    """One ``functions`` row, one field per ``_FUNCTION_COLUMNS`` entry.

    The field names are the file's own key names, camelCase included, so this
    class and that tuple are the same list twice: ``tuple(Function.__slots__) ==
    _FUNCTION_COLUMNS`` is asserted by the tests, which makes a column added,
    dropped or renamed in the writer a reader failure instead of a silent
    omission.  A Python-style rename would be a third spelling of the schema to
    keep in step with the writer's and build_db's.

    ``None`` marks a column build_db allows NULL where NULL means something the
    empty string cannot say: an unknown size is not size 0.  Text columns keep
    ``""``, which is what the writer stores and what every consumer of those
    fields already treats as absent.
    """

    va: int
    name: str
    vaStart: str
    size: int | None
    fileOffset: int | None
    status: str
    module: str
    #: ``build_db`` stores this column without normalizing it, so a catalog may
    #: hand it a string or a list; the reader passes through whatever was
    #: written (frozen) rather than picking one of the two shapes.
    cflags: Any
    symbol: str
    markerType: str
    ghidra_name: str
    list_name: str
    is_thunk: int
    is_export: int
    sha256: str
    files: tuple[str, ...]
    detected_by: tuple[str, ...]
    size_by_tool: Mapping[str, Any]
    textOffset: int | None
    blocker: str
    blockerDelta: int | None
    size_reason: str
    similarity: float | None
    updated_by: str
    updated_at: str


@dataclass(frozen=True, slots=True)
class Global:
    """One ``globals`` row, one field per ``_GLOBAL_COLUMNS`` entry."""

    va: int
    name: str
    decl: str
    files: tuple[str, ...]
    module: str
    size: int
    status: str


@dataclass(frozen=True, slots=True)
class CoverageSnapshot:
    """One target's coverage document, immutable and fully derived.

    ``function_stats`` is read, never recomputed: ``total``, ``covered_bytes``,
    ``matched_bytes`` and ``by_status`` are the numbers
    :func:`_derive_function_stats` produced from the stored function rows, and
    they are the numbers the dashboards' headers show.  A second restatement of
    that aggregate would be the third answer to "what counts as matched".
    """

    target: str
    version: int
    sections: Mapping[str, Section]
    functions: tuple[Function, ...]
    #: The globals table has no matching index here: nothing reads globals by VA
    #: at request rate (the batch lookup walks 346 rows).  Add one when a caller
    #: measures that it needs it.
    globals: tuple[Global, ...]
    verify_results: tuple[Mapping[str, Any], ...]
    history: tuple[Mapping[str, Any], ...]
    function_stats: Mapping[str, Any]
    paths: Mapping[str, Any]
    functions_by_va: Mapping[int, Function] = field(init=False)

    def __post_init__(self) -> None:
        object.__setattr__(
            self, "functions_by_va", MappingProxyType({fn.va: fn for fn in self.functions})
        )


def _text(value: Any) -> str:
    """A text column as ``str``.  TOML's ``""`` stand-in for NULL is ``""``."""
    return value if isinstance(value, str) else ""


def _int(value: Any, default: int) -> int:
    """An integer column, *default* when it is missing or not an int.

    ``bool`` is excluded before ``int``: ``True`` is an int subclass and would
    land as 1.
    """
    if isinstance(value, bool) or not isinstance(value, int):
        return default
    return value


def _opt_int(value: Any) -> int | None:
    """An optional integer column: absent (``""``) and wrong-typed both read None."""
    if isinstance(value, bool) or not isinstance(value, int):
        return None
    return value


def _opt_float(value: Any) -> float | None:
    if isinstance(value, bool) or not isinstance(value, int | float):
        return None
    return float(value)


def _str_tuple(value: Any) -> tuple[str, ...]:
    if isinstance(value, list | tuple):
        return tuple(str(item) for item in value)
    return ()


def _freeze(value: Any) -> Any:
    """Recursively turn a parsed TOML value into an immutable one.

    A nested ``by_status`` dict left mutable would be a hole in the snapshot: one
    caller's edit would show up in the next caller's read, which is the
    guarantee the SQLite read transaction used to give.
    """
    if isinstance(value, dict):
        return MappingProxyType({key: _freeze(item) for key, item in value.items()})
    if isinstance(value, list | tuple):
        return tuple(_freeze(item) for item in value)
    return value


def _table_rows(value: Any, what: str, path: Path) -> list[dict[str, Any]]:
    """*value* as a list of tables, or a ``CoverageTomlError`` naming it."""
    if not isinstance(value, list) or not all(isinstance(row, dict) for row in value):
        raise CoverageTomlError(f"{path}: {what} is not an array of tables")
    return value


def _table(value: Any, what: str, path: Path) -> dict[str, Any]:
    """*value* as a table, or a ``CoverageTomlError`` naming it."""
    if not isinstance(value, dict):
        raise CoverageTomlError(f"{path}: {what} is not a table")
    return value


def _cell(row: dict[str, Any]) -> Cell:
    return Cell(
        start=_int(row.get("start"), 0),
        end=_int(row.get("end"), 0),
        span=_int(row.get("span"), 1),
        state=_text(row.get("state")),
        functions=_str_tuple(row.get("functions")),
        label=_text(row.get("label")),
        parent_function=_text(row.get("parent_function")),
    )


def _section(name: str, table: dict[str, Any], path: Path) -> Section:
    return Section(
        name=name,
        va=_opt_int(table.get("va")),
        size=_int(table.get("size"), 0),
        file_offset=_opt_int(table.get("fileOffset")),
        unit_bytes=_int(table.get("unitBytes"), 0),
        columns=_int(table.get("columns"), 0),
        cells=tuple(
            _cell(row) for row in _table_rows(table.get("cells", []), f"cells of {name}", path)
        ),
    )


def _function(row: dict[str, Any], path: Path) -> Function:
    return Function(
        va=_int(row.get("va"), 0),
        name=_text(row.get("name")),
        vaStart=_text(row.get("vaStart")),
        size=_opt_int(row.get("size")),
        fileOffset=_opt_int(row.get("fileOffset")),
        status=_text(row.get("status")),
        module=_text(row.get("module")),
        cflags=_freeze(row.get("cflags")),
        symbol=_text(row.get("symbol")),
        markerType=_text(row.get("markerType")),
        ghidra_name=_text(row.get("ghidra_name")),
        list_name=_text(row.get("list_name")),
        is_thunk=_int(row.get("is_thunk"), 0),
        is_export=_int(row.get("is_export"), 0),
        sha256=_text(row.get("sha256")),
        files=_str_tuple(row.get("files")),
        detected_by=_str_tuple(row.get("detected_by")),
        size_by_tool=_freeze(_table(row.get("size_by_tool", {}), "size_by_tool", path)),
        textOffset=_opt_int(row.get("textOffset")),
        blocker=_text(row.get("blocker")),
        blockerDelta=_opt_int(row.get("blockerDelta")),
        size_reason=_text(row.get("size_reason")),
        similarity=_opt_float(row.get("similarity")),
        updated_by=_text(row.get("updated_by")),
        updated_at=_text(row.get("updated_at")),
    )


def _global(row: dict[str, Any]) -> Global:
    return Global(
        va=_int(row.get("va"), 0),
        name=_text(row.get("name")),
        decl=_text(row.get("decl")),
        files=_str_tuple(row.get("files")),
        module=_text(row.get("module")),
        size=_int(row.get("size"), 0),
        status=_text(row.get("status")),
    )


def _derive_function_stats(
    functions: tuple[Function, ...], text: Section | None
) -> Mapping[str, Any]:
    """The ``function_stats`` dict, computed from the stored function rows.

    This is the aggregate the removed ``build_db.function_stats`` used to run
    over a throwaway table, with its cursor gone: the same ``FUNCTION_MARKERS``
    code-row filter, the same ``clip_span`` cut at the next function start, the
    same ``MATCHED_STATUSES`` split between identified bytes (every function,
    STUB placeholders included) and matched bytes (EXACT/RELOC, the headline
    figure).

    It is derived rather than stored because it is a pure function of the rows
    already in the file, and a stored copy is a second thing to keep in step on
    every rebuild.  The database stored it because reading it back cost a query;
    here it costs one pass over 600 rows at load.  The two count maps are
    sorted, so a rebuild that writes the same rows in a different order cannot
    change the value.
    """
    rows = [f for f in functions if f.markerType in FUNCTION_MARKERS]
    starts = sorted(f.va for f in rows if f.va is not None)
    by_status: dict[str, int] = {}
    by_module_counts: dict[str, int] = {}
    covered_bytes = 0
    matched_bytes = 0
    for fn in rows:
        status = fn.status or "UNKNOWN"
        by_status[status] = by_status.get(status, 0) + 1
        # Key is the stored module, including "": "GAME" is a real module name,
        # so a blank must not be counted under it.
        module = fn.module or ""
        by_module_counts[module] = by_module_counts.get(module, 0) + 1
        if fn.size is None or fn.va is None:
            continue
        # A negative SIZE is truthy, so it would reach clip_span and move both
        # totals the wrong way; the writer clamps it to 0 on the way in.
        size = clip_span(starts, fn.va, max(fn.size, 0))
        covered_bytes += size
        if status in MATCHED_STATUSES:
            matched_bytes += size
    return MappingProxyType(
        {
            "total": len(rows),
            # Identified bytes: every function, STUB placeholders included.
            "covered_bytes": covered_bytes,
            # EXACT/RELOC only — the headline coverage metric.
            "matched_bytes": matched_bytes,
            "total_bytes": text.size if text is not None else 0,
            "by_status": MappingProxyType(dict(sorted(by_status.items()))),
            "by_module_counts": MappingProxyType(dict(sorted(by_module_counts.items()))),
        }
    )


def _snapshot(path: Path, doc: dict[str, Any], target: str) -> CoverageSnapshot:
    """Build the snapshot from a parsed document, checking both target names.

    The document names its target twice (top level and the filename), and the
    two are written from one value.  They disagreeing means the file was renamed
    or hand-edited, and a request for ``a`` answered with ``b``'s coverage is the
    one failure mode a dashboard cannot show the reader.
    """
    # `type(...) is int`, not isinstance: a float 1.0 and True both compare equal
    # to 1 and neither is this schema's version.
    version = doc.get("version")
    if type(version) is not int or version != _TOML_VERSION:
        raise CoverageTomlError(f"{path}: version is {version!r}, expected {_TOML_VERSION}")
    doc_target = _text(doc.get("target"))
    if doc_target and doc_target != target:
        raise CoverageTomlError(f"{path}: target is {doc_target!r}, expected {target!r}")

    sections_doc = _table(doc.get("sections", {}), "sections", path)
    sections = {
        name: _section(name, _table(table, f'sections."{name}"', path), path)
        for name, table in sections_doc.items()
    }
    functions = tuple(
        _function(row, path) for row in _table_rows(doc.get("functions", []), "functions", path)
    )
    globals_ = tuple(_global(row) for row in _table_rows(doc.get("globals", []), "globals", path))
    verify_results = tuple(
        _freeze(row) for row in _table_rows(doc.get("verify_results", []), "verify_results", path)
    )
    history = tuple(_freeze(row) for row in _table_rows(doc.get("history", []), "history", path))
    metadata = _table(doc.get("metadata", {}), "metadata", path)
    paths = _freeze(_table(metadata.get("paths", {}), "paths", path))
    return CoverageSnapshot(
        target=doc_target or target,
        version=version,
        sections=MappingProxyType(sections),
        functions=functions,
        globals=globals_,
        verify_results=verify_results,
        history=history,
        function_stats=_derive_function_stats(functions, sections.get(".text")),
        paths=paths,
    )


def _read_document(path: Path, target: str) -> CoverageSnapshot:
    """Read and validate one document.  Every failure is a ``CoverageTomlError``.

    An unreadable file, malformed TOML, a foreign ``version`` and a schema
    violation all land in one exception type, because a dashboard's answer to
    all four is the same: this target is not readable, show the others.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        raise CoverageTomlError(f"{path}: cannot read ({exc})") from exc
    try:
        doc = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        # A file torn by anything other than atomic_write_text lands here too.
        raise CoverageTomlError(f"{path}: malformed TOML ({exc})") from exc
    return _snapshot(path, doc, target)


# Memoized directory scan: ((db_dir, ((name, mtime_ns, size, ino), ...)), snapshots).
# The key is every input the answer has — the directory and the stat of every
# file in it — so a rebuilt file, an added target and a removed one all
# invalidate.  load_all_coverage runs on the request path and re-reading and
# re-parsing a 1.25 MB document per request is pure waste; one stat per
# candidate file replaces it.  The tuple swap is atomic under the GIL and a
# racing recomputation yields an equal value, so no lock: the worst case is a
# duplicate parse.  Same pattern, same reason as recoverage's _db_path memo.
# Callers use the returned object's identity as their own cache key, so an
# unchanged directory returns THE SAME snapshots, not equal copies.
_ALL_CACHE: (
    tuple[tuple[Path, tuple[tuple[str, int, int, int], ...]], dict[str, CoverageSnapshot]] | None
) = None


def _stat_key(db_directory: Path) -> tuple[tuple[str, int, int, int], ...]:
    """``(name, mtime_ns, size, ino)`` for every ``coverage-*.toml`` in the directory.

    Sorted, because a directory listing's order is not a fact about the files.
    A file that vanishes between the listing and the stat is skipped: the next
    call's key differs, so the miss is caught then.

    The inode is what catches a document replaced by a same-size rename-over
    inside one mtime tick (a ``cp -p`` restore, a git checkout of a restored
    file, a coarse-timestamp filesystem), which mtime and size alone cannot
    see; this matches every other per-file memo in the tree
    (``verify_hash._SOURCE_MEMO``, ``metadata_doc``, ``utils.read_source_text``).
    """
    entries: list[tuple[str, int, int, int]] = []
    for path in db_directory.glob(f"{_FILENAME_PREFIX}*{_FILENAME_SUFFIX}"):
        try:
            st = path.stat()
        except OSError:
            continue
        entries.append((path.name, st.st_mtime_ns, st.st_size, st.st_ino))
    entries.sort()
    return tuple(entries)


def load_all_coverage_from(db_directory: Path) -> dict[str, CoverageSnapshot]:
    """``load_all_coverage`` for a caller that already holds the directory.

    ``load_all_coverage`` takes a project ROOT and resolves ``[project].db_dir``
    (or ``<root>/db``) itself, which is the right call for a tool started in a
    project.  A dashboard can also be pointed straight at a directory — the
    recoverage ``RECOVERAGE_DB`` override names one — and deriving a root from
    that path to let this module derive the directory back loses whenever the
    parent directory has its own ``rebrew-project.toml`` naming a different db
    dir.  One glob, keyed on the files themselves, is the whole difference.
    """
    global _ALL_CACHE
    db_directory = Path(db_directory)
    key = (db_directory, _stat_key(db_directory))
    cached = _ALL_CACHE
    if cached is not None and cached[0] == key:
        return cached[1]
    snapshots: dict[str, CoverageSnapshot] = {}
    for name, _mtime_ns, _size, _ino in key[1]:
        target = name[len(_FILENAME_PREFIX) : -len(_FILENAME_SUFFIX)]
        path = db_directory / name
        try:
            snapshots[target] = _read_document(path, target)
        except CoverageTomlError as exc:
            log.warning("coverage_toml: skipping %s: %s", path, exc)
    _ALL_CACHE = (key, snapshots)
    return snapshots


def load_coverage_from(db_directory: Path, target: str) -> CoverageSnapshot:
    """One target's snapshot from an explicit *db_directory*.

    The directory-taking twin of :func:`load_coverage`, for the same caller:
    a dashboard whose database location is configuration, not a project root.
    """
    if not target or Path(target).name != target:
        raise CoverageTomlError(f"{target!r} is not a target name")
    path = Path(db_directory) / f"{_FILENAME_PREFIX}{target}{_FILENAME_SUFFIX}"
    return _read_document(path, target)


def load_all_coverage(root_dir: Path) -> dict[str, CoverageSnapshot]:
    """Every target in *root_dir*'s db directory, keyed by target name.

    Returns ``{}`` when the directory holds no ``coverage-*.toml``.  One
    unreadable document is skipped with a warning naming the file and the
    reason, never raised: a dashboard showing two of three targets beats a 500.
    An unchanged directory returns the previously built mapping, so callers can
    use ``is`` as their own cache key.
    """
    return load_all_coverage_from(_db_directory(root_dir))


def load_coverage(root_dir: Path, target: str | None = None) -> CoverageSnapshot:
    """Load one target's snapshot from ``db/coverage-<target>.toml``.

    Raises :class:`CoverageTomlError` when the file is missing, when its
    ``version`` is not :data:`_TOML_VERSION`, when the TOML is malformed, and
    when the document is not shaped like this schema.

    *target* ``None`` means the project has exactly one target: the sole
    ``coverage-*.toml`` is returned and any other number is an error naming the
    candidates.  Resolving a default out of ``rebrew-project.toml`` instead
    would answer with a target the caller did not name, which is the one thing a
    per-target reader must not do.

    A *target* carrying a path separator is refused rather than resolved: the
    dashboards take a target id from the request path, and the SQLite reader
    could not be made to read a foreign database by spelling a VA or a target
    oddly.  A filename can.
    """
    db_directory = _db_directory(root_dir)
    if target is None:
        snapshots = load_all_coverage(root_dir)
        if len(snapshots) != 1:
            found = ", ".join(sorted(snapshots)) or "none"
            raise CoverageTomlError(
                f"{db_directory}: expected exactly one coverage file for target=None, "
                f"found {len(snapshots)} ({found})"
            )
        return next(iter(snapshots.values()))
    if not target or Path(target).name != target:
        raise CoverageTomlError(f"{target!r} is not a target name")
    return _read_document(db_directory / f"{_FILENAME_PREFIX}{target}{_FILENAME_SUFFIX}", target)
