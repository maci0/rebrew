def _function_rows(target_name: str, data: dict[str, Any]) -> list[tuple[Any, ...]]:
    """Build the ``functions`` rows, skipping rows with no parseable VA.

    Field-for-field the row the removed SQLite writer inserted, so a document
    written before the move reads the same as one written after it.  The clamps
    exist because that writer's CHECK constraints rejected a whole rebuild on
    one stray negative or bool; a text file has no CHECKs, so they are kept to
    hold the two spellings of the same catalog value together rather than
    because the TOML needs them.
    """
    rows: list[tuple[Any, ...]] = []
    bad_va = 0
    for va, fn in data.get("functions", {}).items():
        if not isinstance(fn, dict):
            bad_va += 1
            continue
        # -1, not 0, marks "unparseable": VA 0 is a real address on 16-bit
        # targets.
        va_int = parse_int(va, -1)
        if va_int < 0:
            va_int = parse_int(fn.get("vaStart"), -1)
        if va_int < 0:
            bad_va += 1
            continue

        va_start_text = str(fn.get("vaStart") or f"0x{va_int:08x}")
        # bool is an int subclass, so True would land as size=1.
        fn_size = fn.get("size")
        if isinstance(fn_size, bool) or (fn_size is not None and not isinstance(fn_size, int)):
            fn_size = None
        elif isinstance(fn_size, int) and fn_size < 0:
            fn_size = 0
        file_off = fn.get("fileOffset")
        if isinstance(file_off, bool) or (file_off is not None and not isinstance(file_off, int)):
            file_off = None
        elif isinstance(file_off, int) and file_off < 0:
            file_off = 0
        text_off = fn.get("textOffset")
        if isinstance(text_off, bool) or (text_off is not None and not isinstance(text_off, int)):
            text_off = None
        elif isinstance(text_off, int) and text_off < 0:
            text_off = 0
        blocker_delta = fn.get("blockerDelta")
        if isinstance(blocker_delta, bool) or (
            blocker_delta is not None and not isinstance(blocker_delta, int)
        ):
            blocker_delta = None
        elif isinstance(blocker_delta, int) and blocker_delta < 0:
            blocker_delta = 0
        fn_marker = str(fn.get("markerType") or "FUNCTION")
        if fn_marker not in VALID_MARKERS:
            fn_marker = "FUNCTION"
        fn_status = canonical_status(str(fn.get("status") or "UNKNOWN"))
        if fn_status not in FUNCTION_DB_STATUSES:
            fn_status = "UNKNOWN"
        rows.append(
            (
                target_name,
                va_int,
                str(fn.get("name") or ""),
                va_start_text,
                fn_size,
                file_off,
                fn_status,
                str(fn.get("module") or fn.get("origin") or ""),
                fn.get("cflags"),
                fn.get("symbol"),
                fn_marker,
                fn.get("ghidra_name"),
                fn.get("list_name"),
                int(bool(fn.get("is_thunk", False))),
                int(bool(fn.get("is_export", False))),
                fn.get("sha256"),
                json.dumps(fn.get("files", [])),
                json.dumps(fn.get("detected_by", [])),
                json.dumps(fn.get("size_by_tool", {})),
                text_off,
                fn.get("blocker", ""),
                blocker_delta,
                fn.get("size_reason", ""),
                clamp_unit_interval(fn.get("similarity")),
                str(fn.get("updated_by") or ""),
                str(fn.get("updated_at") or ""),
            )
        )
    if bad_va:
        console.print(
            f"[yellow]warning:[/yellow] {target_name}: skipped {bad_va} "
            "function row(s) with unparseable VA (no valid key or vaStart)"
        )
    return rows


def _global_rows(target_name: str, data: dict[str, Any]) -> list[tuple[Any, ...]]:
    """Build the ``globals`` rows, skipping rows with no parseable VA.

    Field-for-field the row the removed SQLite writer inserted; see
    :func:`_function_rows` for why the clamps stay.
    """
    rows: list[tuple[Any, ...]] = []
    bad_va = 0
    for va, g in data.get("globals", {}).items():
        if not isinstance(g, dict):
            bad_va += 1
            continue
        # -1, not 0: 16-bit targets place data at segment 0.
        va_int = parse_int(va, -1)
        if va_int < 0:
            va_int = parse_int(g.get("va"), -1)
        if va_int < 0:
            bad_va += 1
            continue
        g_size = g.get("size")
        if isinstance(g_size, bool) or not isinstance(g_size, int):
            g_size = _GLOBAL_DEFAULT_SIZE
        elif g_size < 0:
            g_size = 0
        g_status = str(g.get("status") or "").strip().upper()
        if g_status not in GLOBAL_DB_STATUSES:
            g_status = ""
        rows.append(
            (
                target_name,
                va_int,
                str(g.get("name") or ""),
                str(g.get("decl") or ""),
                json.dumps(g.get("files", [])),
                str(g.get("module") or g.get("origin") or ""),
                g_size,
                g_status,
            )
        )
    if bad_va:
        console.print(
            f"[yellow]warning:[/yellow] {target_name}: skipped "
            f"{bad_va} global row(s) with unparseable VA "
            "(no valid key or va field)"
        )
    return rows


def _section_table(sec_name: str, sec: dict[str, Any]) -> list[str]:
    """Render one ``[sections."<name>"]`` table: the scalars, then the cells.

    The section's name is the table's key, not a field inside it, so the five
    scalars here are the ``sections`` row's other columns.
    """
    values = (
        clamp_nonneg_int(sec.get("va")),
        clamp_nonneg_int(sec.get("size")),
        clamp_nonneg_int(sec.get("fileOffset")),
        # The same fallback the sections row uses: a hand-edited 0 aborts the
        # SQLite rebuild and renders a zero-width grid here.
        positive_int_or(sec.get("unitBytes"), DEFAULT_GRID_GEOMETRY),
        positive_int_or(sec.get("columns"), DEFAULT_GRID_GEOMETRY),
    )
    lines = [f"[sections.{_key(sec_name)}]"]
    lines.extend(_kv(name, value) for name, value in zip(_SECTION_COLUMNS, values, strict=True))
    cell_rows = dedupe_cell_rows(
        [
            normalize_cell_row("", sec_name, cell)
            for cell in sec.get("cells", [])
            if isinstance(cell, dict)
        ],
        target_name=sec_name,
        sec_name=sec_name,
    )
    lines.extend(_kv_block("cells", [_rows_from(_CELL_COLUMNS, r) for r in cell_rows]))
    return lines


def _merge_history(
    previous_functions: Any, previous_history: Any, fn_rows: Sequence[tuple[Any, ...]]
) -> list[dict[str, Any]]:
    """Carry previous history forward and append this build's status deltas.

    The old writer snapshotted the statuses already stored, appended one row
    per change, and kept the newest ``HISTORY_RETENTION`` per target.  Here
    the previous file's ``functions`` array is that snapshot and its ``history``
    array is the table, so the same three steps give the same answer without a
    transaction.
    """
    old_statuses: dict[Any, Any] = {}
    if isinstance(previous_functions, list):
        old_statuses = {
            row["va"]: row["status"]
            for row in previous_functions
            if isinstance(row, dict) and isinstance(row.get("va"), int)
        }
    carried: list[dict[str, Any]] = (
        [dict(row) for row in previous_history if isinstance(row, dict)]
        if isinstance(previous_history, list)
        else []
    )

    now_iso = datetime.now(UTC).isoformat()
    for row in fn_rows:
        new_va, new_status, updated_by = row[1], row[6], row[24]
        old_status = old_statuses.get(new_va)
        if old_status is not None and old_status != new_status:
            old_s = canonical_status(str(old_status or "UNKNOWN"))
            if old_s not in FUNCTION_DB_STATUSES:
                old_s = "UNKNOWN"
            new_s = canonical_status(str(new_status or "UNKNOWN"))
            if new_s not in FUNCTION_DB_STATUSES:
                new_s = "UNKNOWN"
            carried.append(
                {
                    "va": max(0, parse_int(new_va, 0)),
                    "old_status": old_s,
                    "new_status": new_s,
                    "changed_at": now_iso,
                    "updated_by": updated_by or "",
                }
            )
    # Retention: the newest HISTORY_RETENTION rows.  ``sorted`` is stable, so
    # two rows sharing a changed_at keep write order and the file stays
    # byte-identical across runs that changed nothing.
    carried.sort(key=lambda r: str(r.get("changed_at", "")))
    return carried[-HISTORY_RETENTION:]


