def _measurement(value: Any) -> Any:
    """A stored measurement as a freshly built row spells it.

    TOML has no null: the writer stores an absent ``byte_delta`` as ``""``.  A
    freshly clamped row spells it ``None``, and the two must compare equal or
    every rebuild would read an unchanged verdict as a changed one and restamp
    it.  No measurement is ever a real empty string, so the fold is unambiguous.
    """
    return None if value == "" else value


def _previous_measured(previous: dict[str, Any]) -> dict[int, tuple[Any, ...]]:
    """The previous document's ``verify_results`` as :func:`import_verify_rows` wants them.

    The removed SQLite writer read the same mapping from its own query over
    ``verify_results`` — each VA's five measurement fields beside the stamp it
    was measured at — because a row whose measurements did not move keeps its
    earlier ``verified_at``.  A TOML file holds both facts in its
    ``verify_results`` rows, so the mapping is rebuilt here instead of queried.
    """
    measured: dict[int, tuple[Any, ...]] = {}
    rows = previous.get("verify_results")
    if not isinstance(rows, list):
        return measured
    for row in rows:
        if not isinstance(row, dict):
            continue
        va = row.get("va")
        # bool is an int subclass, and either would key a row no fresh row can
        # match; the row is skipped rather than raising, because this reads a
        # hand-editable file.
        if isinstance(va, bool) or not isinstance(va, int):
            continue
        measured[va] = (
            tuple(_measurement(row.get(column)) for column in _VERIFY_RESULTS_COLUMNS[2:]),
            str(row.get("verified_at") or ""),
        )
    return measured


def _read_previous(path: Path) -> dict[str, Any]:
    """Read the previous document, or ``{}`` when there is nothing to read.

    Missing, unreadable and unparseable all collapse to ``{}``.  A document of
    the wrong *version* is still returned as-is: :func:`render_coverage_toml`
    is what rejects it, so the rule holds for every caller rather than only for
    the one that went through a file.
    """
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {}
    except (OSError, ValueError) as exc:
        # tomllib.TOMLDecodeError subclasses ValueError; a UnicodeDecodeError
        # does too.  A half-written file lands in the same place.  Warn, not
        # debug: the caller rebuilds from this and drops the whole history
        # array, so a silent ``{}`` resets every chart on the dashboard.
        log.warning(
            "coverage_toml: cannot read %s (%s); the rebuild carries no history",
            path,
            exc,
        )
        return {}


#: One thread lock per target name; the cross-process half is the ``flock`` in
#: :func:`_coverage_write_lock`.  Both dashboards regenerate from WSGI worker
#: threads, so an in-process lock is not optional.
_COVERAGE_WRITE_LOCKS: dict[str, threading.Lock] = {}
_COVERAGE_WRITE_LOCKS_LOCK = threading.Lock()


@contextlib.contextmanager
def _coverage_write_lock(root_dir: Path, target_name: str) -> Iterator[None]:
    """Hold the coverage read-modify-write lock for *target_name*.

    Same discipline as :func:`rebrew.verify_cache._verify_cache_write_lock`: a
    thread lock plus an advisory ``flock`` sidecar, so an in-process dashboard
    regen and a second process's ``build-db`` cannot interleave.  The sidecar
    lives under ``.rebrew/`` beside the verify cache's rather than in ``db/``,
    which holds the delivered documents and nothing else.

    Separate from the metadata write lock: the coverage document is derived
    output, rewritten whole from the catalog, and shares no file with
    ``rebrew-functions.toml`` or ``rebrew-data.toml``.
    """
    with _COVERAGE_WRITE_LOCKS_LOCK:
        lock = _COVERAGE_WRITE_LOCKS.get(target_name)
        if lock is None:
            lock = _COVERAGE_WRITE_LOCKS[target_name] = threading.Lock()
    with lock, file_lock(root_dir / ".rebrew" / f"coverage-{target_name}.toml.lock"):
        yield


