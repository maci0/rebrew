"""coverage_toml.py – clear-text TOML coverage output for a catalog snapshot.

The normalizers live in :mod:`rebrew.build_db`, which computed every value in
pure Python before the SQLite writer it also held bound it to a column.  This
module imports those normalizers rather than restating them, so the document and
the catalog snapshot cannot report different facts about the same
the in-process catalog dict — a second implementation of the cell clamp or the status
sanitizer is exactly the drift this file exists to remove.

Only facts are stored.  The removed ``build_db`` materialized per-section
buckets, the per-section cell JSON and the ``summary`` blob because a SQL reader
wanted them cheaply; a TOML reader re-derives every one of them from ``sections``
+ ``cells``, and a stored copy is a second place for the two writers to disagree.

Two consequences of writing TOML are load-bearing and stated once here:

* **TOML has no null.**  ``None`` is written as ``""``, so a reader cannot tell
  a NULL column from an empty one.  Every NULL in this schema is an optional
  field (``label``, ``parent_function``, a section's ``va``/``fileOffset``, a
  function's ``size``/``similarity``), and every consumer of those fields
  already treats missing and empty alike.
* **A bare key belongs to the table above it.**  The bulk arrays are therefore
  written BEFORE the first ``[table]`` header, so they land at the document top
  level; written after ``[sections."…"]`` they would silently nest inside the
  last section instead of beside it.
"""

