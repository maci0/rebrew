"""Emit the per-target source list a CMake build must compile.

A glob (``src/shared/*.c``) over-includes: a shared tree holds every
target's TUs, and a target must compile only files bound to its module
in the function/data stores or source-purpose metadata — a GOLD-only TU linked into server.dll
is a composition break (duplicate symbols at best, foreign bytes at
worst).  ``rebrew build cmake-sources`` partitions the tree by marker and writes
a CMake include setting ``<VAR>`` to exactly that target's files:

    execute_process(COMMAND ${REBREW} cmake-sources -o ${CMAKE_BINARY_DIR}/rebrew-sources.cmake)
    include(${CMAKE_BINARY_DIR}/rebrew-sources.cmake)
    add_library(server_dll SHARED ${REBREW_SOURCES})

``--var`` renames the variable (default ``REBREW_SOURCES``); ``--target``
picks the module (default: current target). Unbound ``.c`` files
(e.g. shared link helpers) are included —
they belong to every target that globs them, same as before.
"""

from __future__ import annotations

from pathlib import Path

import typer

from rebrew.cli import (
    TargetOption,
    console,
    json_print,
    require_config,
)
from rebrew.config import ProjectConfig
from rebrew.function_providers import bind_library_source
from rebrew.metadata.bindings import SourceBinding, read_source_bindings
from rebrew.metadata.functions import load_metadata
from rebrew.sources import iter_sources, target_marker
from rebrew.utils import (
    atomic_write_text,
    preset_module_key,
)

#: The module docstring is design notes, not help: it is RST, and Rich would
#: render its double backticks and emphasis markers literally.
app = typer.Typer(
    add_completion=False,
    help="Emit the per-target source list a CMake build must compile.",
    rich_markup_mode="rich",
    epilog=(
        "[bold]Examples:[/bold]\n\n"
        "  rebrew build cmake-sources -o build/rebrew-sources.cmake · Write the source list\n\n"
        "  rebrew build cmake-sources --var TARGET_SOURCES · Set a different CMake variable\n\n"
        "  rebrew build cmake-sources --dry-run · Print the list without writing\n\n"
        "  rebrew build cmake-sources --target server --json · Machine-readable, one target\n\n"
        "[dim]From CMakeLists.txt:[/dim]\n\n"
        "  execute_process(COMMAND ${REBREW} cmake-sources -o "
        "${CMAKE_BINARY_DIR}/rebrew-sources.cmake)\n"
        "  include(${CMAKE_BINARY_DIR}/rebrew-sources.cmake)\n\n"
        "[dim]Canonical identities and source-purpose metadata select each target's "
        "translation units. A glob over src/ would link another "
        "target's TUs in.[/dim]"
    ),
)

HEADER = """# Per-target sources from canonical Rebrew metadata.
# Generated by `rebrew build cmake-sources` — re-run after adding, moving,
# or changing target bindings. Function/data identities and source-purpose
# metadata select target files; unbound helpers are shared across targets.
# Configured external archives are listed as REBREW_EXTERNAL_LIBS.
"""


def collect(cfg: ProjectConfig, marker: str) -> tuple[list[Path], list[Path]]:
    """``(own, foreign)`` absolute source paths for *marker*.

    *own* holds target-bound identities, target-scoped support files, and
    unbound helpers. *foreign* holds files bound only to other targets.
    """
    from rebrew.metadata.source_provenance import load_source_files

    own: list[Path] = []
    foreign: list[Path] = []
    # Explicit compiled-library bindings are project-root relative. The pure-C
    # parser uses metadata-relative paths, so retain every module's bindings
    # before deciding a body is an unannotated helper shared by all targets.
    library_entries: dict[Path, list[SourceBinding]] = {}
    for (module, va), row in load_metadata(cfg.metadata_dir, deepcopy=False).items():
        stored = str(row.get("file", ""))
        if (
            not va
            or row.get("kind") != "LIBRARY"
            or Path(stored).suffix.casefold() not in {".c", ".cpp", ".cc", ".cxx"}
        ):
            continue
        bound = bind_library_source(cfg, SourceBinding(module=module, va=va, kind="LIBRARY"), row)
        source = (cfg.reversed_dir / bound.filepath).resolve()
        library_entries.setdefault(source, []).append(bound)
    for src in iter_sources(cfg.reversed_dir, cfg):
        anns = [a for a in read_source_bindings(src, metadata_dir=cfg.metadata_dir) if a.va]
        anns.extend(library_entries.get(src.resolve(), []))
        if not anns:
            relative = src.resolve().relative_to(cfg.metadata_dir.resolve()).as_posix()
            modules = {
                record.module
                for record in load_source_files(cfg.metadata_dir)
                if record.file == relative
            }
            if not modules or preset_module_key(marker) in modules:
                own.append(src.resolve())
            else:
                foreign.append(src.resolve())
            continue
        if any(preset_module_key(a.module) == preset_module_key(marker) for a in anns):
            own.append(src.resolve())
        else:
            foreign.append(src.resolve())
    return sorted(own), sorted(foreign)


@app.callback(invoke_without_command=True)
def main(
    output: Path = typer.Option(
        Path("build/rebrew-sources.cmake"), "--output", "-o", help="CMake include to write"
    ),
    var: str = typer.Option(
        "REBREW_SOURCES", "--var", help="CMake variable to set with the source list"
    ),
    dry_run: bool = typer.Option(False, "--dry-run", help="Preview changes without writing"),
    json_output: bool = typer.Option(False, "--json", help="Output results as JSON"),
    target: str | None = TargetOption,
) -> None:
    """Write the target's source list as a CMake include."""
    cfg = require_config(target=target, json_mode=json_output)
    marker = target_marker(cfg) or cfg.target_name
    own, foreign = collect(cfg, marker)

    rels = [p.relative_to(cfg.root).as_posix() for p in own]
    # Config order IS link order ("link it at the right place" — e.g. a
    # static LIBCMT last), so dedupe without sorting.
    external: list[str] = []
    for spec in (getattr(cfg, "external_libs", None) or {}).values():
        s = (spec or "").strip()
        if s and s not in external:
            external.append(s)
    lines = [
        HEADER,
        "set_property(DIRECTORY APPEND PROPERTY CMAKE_CONFIGURE_DEPENDS\n"
        '  "${CMAKE_CURRENT_SOURCE_DIR}/rebrew-project.toml"\n',
    ]
    for name in ("rebrew-functions.toml", "rebrew-data.toml", "rebrew-source.toml"):
        metadata = (cfg.metadata_dir / name).relative_to(cfg.root).as_posix()
        lines.append(f'  "${{CMAKE_CURRENT_SOURCE_DIR}}/{metadata}"\n')
    lines.append(")\n\n")
    lines.append(f"set({var}\n")
    for rel in rels:
        lines.append(f'  "${{CMAKE_CURRENT_SOURCE_DIR}}/{rel}"\n')
    lines.append(")\n")
    if external:
        lines.append("\nset(REBREW_EXTERNAL_LIBS\n")
        for spec in external:
            lines.append(f'  "{spec}"\n')
        lines.append(")\n")
    text = "".join(lines)

    if not json_output and foreign and not dry_run:
        console.print(
            f"[dim]cmake-sources: {len(foreign)} file(s) carry no {marker} marker "
            f"and are excluded from the build[/dim]"
        )
    if dry_run:
        if not json_output:
            print(text)
    else:
        atomic_write_text(output, text)
    if json_output:
        json_print(
            {
                "target": cfg.target_name,
                "marker": marker,
                "variable": var,
                "written": None if dry_run else str(output),
                "files": rels,
                "external_libs": external,
                "excluded": [p.relative_to(cfg.root).as_posix() for p in foreign],
            }
        )
    elif not dry_run:
        console.print(f"[green]cmake-sources:[/green] wrote {output} ({len(rels)} source files)")


def main_entry() -> None:
    """Run the Typer CLI application."""
    from rebrew.cli import run_standalone

    run_standalone(main)


if __name__ == "__main__":
    main_entry()
